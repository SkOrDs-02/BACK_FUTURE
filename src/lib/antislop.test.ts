import { describe, expect, it } from "vitest";
import { findSlop } from "./antislop";

describe("findSlop", () => {
  it("returns nothing for clean text", () => {
    expect(
      findSlop("Телескоп Джеймса Вебба запустили 2021 року. Він бачить інфрачервоне світло."),
    ).toEqual([]);
  });

  it.each([
    ["Космос — це далеко.", "довге тире «—»"],
    ["Це не просто телескоп, а машина часу.", "«не просто X, а Y»"],
    ["Це не про гроші, це про довіру.", "«це не про X, це про Y»"],
    ["Чи змінило це науку? Так. І ось чому.", "риторичне питання з самовідповіддю"],
    ["Потужний, гнучкий і масштабований інструмент.", "потрійні прикметники"],
    ["Нові, швидкі, дешеві ракети.", "потрійні прикметники"],
    ["Варто зазначити, що це важливо.", "«варто зазначити»"],
    ["У сучасному світі все швидко.", "«у сучасному світі»"],
    ["Запуск здійснюється з Байконура.", "канцелярит «здійснюється/забезпечується»"],
    [
      "Живлення забезпечують панелі, контроль забезпечується автоматикою.",
      "канцелярит «здійснюється/забезпечується»",
    ],
  ])("flags %s", (text, rule) => {
    expect(findSlop(text)).toContain(rule);
  });

  it("keeps en dash ranges, two adjectives and lists of place names", () => {
    expect(findSlop("Ера 1991–1995. Стабільні, консенсусні факти.")).toEqual([]);
    expect(findSlop("Акції пройшли в Києві, Львові й Харкові.")).toEqual([]);
  });

  it("reports each rule once", () => {
    expect(findSlop("А — б — в")).toEqual(["довге тире «—»"]);
  });
});
